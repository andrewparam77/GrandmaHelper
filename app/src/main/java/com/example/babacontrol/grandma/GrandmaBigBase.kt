    // ============================================================
    //  СТЕММИНГ — отрезаем окончания
    // ============================================================
    private fun stem(word: String): String {
        var w = word.lowercase(Locale("ru", "RU"))
        w = w.replace(Regex("[^а-яёa-z0-9]"), "")
        if (w.length < 3) return w

        // синоним — если есть
        synonyms[w]?.let { return it }

        // Окончания (от длинных к коротким)
        val suffixes = listOf(
            "аться", "иться", "ыться", "еться",
            "ать", "ить", "еть", "ыть", "уть", "ять",
            "ает", "ают", "аем", "ает", "аешь",
            "ить", "ит", "ишь", "им", "ите", "ят",
            "ение", "ание", "ие", "ье", "ей",
            "ой", "ей", "ая", "яя", "ые", "ие", "ых", "их", "ое", "ее", "ыми", "ими",
            "ом", "ем", "ам", "ям", "ах", "ях", "ов", "ев",
            "а", "я", "ы", "и", "у", "ю", "е", "о", "ь", "й"
        )
        for (s in suffixes) {
            if (w.endsWith(s) && w.length - s.length >= 3) {
                return w.substring(0, w.length - s.length)
            }
        }
        return w
    }

    // ============================================================
    //  РАЗБОР ТЕКСТА НА ЗНАЧИМЫЕ СЛОВА
    // ============================================================
    private fun extractKeywords(text: String): Set<String> {
        return text.lowercase(Locale("ru", "RU"))
            .split(Regex("[^а-яёa-z0-9]+"))
            .filter { it.length >= 3 }
            .filter { it !in stopWords }
            .map { stem(it) }
            .filter { it.length >= 3 }
            .toSet()
    }

    // ============================================================
    //  ПОИСК ОТВЕТА
    // ============================================================
    fun findAnswer(question: String): String? {
        val q = question.lowercase(Locale("ru", "RU")).trim()
        if (q.isEmpty()) return null

        // ============ ПРОХОД 1: ТОЧНОЕ ВХОЖДЕНИЕ КЛЮЧА ============
        // Самый надёжный — если ключевая фраза встречается в вопросе целиком
        for ((keys, answer) in facts) {
            for (k in keys) {
                if (q.contains(k)) {
                    return answer
                }
            }
        }

        // ============ ПРОХОД 2: ПО ЗНАЧИМЫМ СЛОВАМ ============
        val qWords = extractKeywords(q)
        if (qWords.isEmpty()) return null

        var bestAnswer: String? = null
        var bestScore = 0.0

        for ((keys, answer) in facts) {
            for (k in keys) {
                val kWords = extractKeywords(k)
                if (kWords.isEmpty()) continue

                var matches = 0
                for (kw in kWords) {
                    if (qWords.contains(kw)) matches++
                }

                if (matches == 0) continue

                // Оценка: сколько процентов ключевых слов совпало
                val score = matches.toDouble() / kWords.size.toDouble()

                // Учитываем абсолютное совпадение тоже
                // Если в ключе 1 слово и оно совпало — это вес 1.0
                // Если в ключе 2 слова и 1 совпало — 0.5
                if (score > bestScore) {
                    bestScore = score
                    bestAnswer = answer
                }
            }
        }

        // Порог 50% — если совпало меньше половины ключевых слов, не отвечаем
        if (bestScore < 0.5) return null

        return bestAnswer
    }

